#!/usr/bin/env python3
"""Emit the kernel-side owner-root policy source from signed headers.

The verified block driver links against three symbols: the trusted key anchor,
the policy array and its count. They were generated as zeroed stubs while the
root image had no policy; this file replaces them with the signed headers the
owner key produced, so publication is authenticated instead of refused.
"""
import json
import pathlib
import sys

KEY_BYTES = 395
HEADER_BYTES = 160
SIGNATURE_BYTES = 384


def anchor(public_key):
    """VROOTKEY || modulus(384) || 0x010001, matching manifest.public_anchor."""
    import subprocess
    line = subprocess.check_output(
        ["openssl", "rsa", "-pubin", "-in", str(public_key), "-modulus", "-noout"], text=True)
    modulus = bytes.fromhex(line.strip().split("=", 1)[1])
    if len(modulus) != 384:
        raise SystemExit(f"unexpected modulus length {len(modulus)}")
    return b"VROOTKEY" + modulus + b"\x01\x00\x01"


def emit_array(name, data, indent="  "):
    lines = [f"{indent}/* {name}: {len(data)} bytes */"]
    for start in range(0, len(data), 16):
        chunk = data[start:start + 16]
        lines.append(indent + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    return lines


def main():
    policies_json, public_key, output = sys.argv[1], sys.argv[2], sys.argv[3]
    records = json.loads(pathlib.Path(policies_json).read_text())
    key = anchor(public_key)
    if len(key) != KEY_BYTES:
        raise SystemExit(f"anchor is {len(key)} bytes, expected {KEY_BYTES}")

    out = []
    out.append("// SPDX-License-Identifier: BSD-2-Clause-Patent")
    out.append("// Owner-root policy generated by peridot tools/emit-owner-policies.py.")
    out.append("// Replace this file by regenerating, never by editing the byte arrays.")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("// NativeVerifiedBlockPolicy comes from the storage bindings; only the data is defined here.")
    out.append("")
    out.append('extern "C" {')
    out.append("")
    out.append(f"const uint8_t verified_root_key[{KEY_BYTES}] = {{")
    out += emit_array("trusted key anchor", key)
    out.append("};")
    out.append("")
    names = []
    for record in records:
        data = bytes.fromhex(record["header"]) + bytes.fromhex(record["signature"])
        if len(data) != HEADER_BYTES + SIGNATURE_BYTES:
            raise SystemExit(f"{record['name']}: envelope is {len(data)} bytes")
        ident = record["name"].replace(" ", "_")
        names.append(ident)
        out.append(f"static const uint8_t policy{ident}[{len(data)}] = {{")
        out += emit_array(record["name"], data)
        out.append("};")
        out.append("")
    out.append("const NativeVerifiedBlockPolicy verified_root_policies[] = {")
    for ident in names:
        out.append(f"  {{policy{ident}, {HEADER_BYTES + SIGNATURE_BYTES}}},")
    out.append("};")
    out.append(f"const uint64_t verified_root_policy_count = {len(names)};")
    out.append("")
    out.append("}  // extern \"C\"")
    out.append("")
    emit_assembly(records, key, output)



def emit_assembly(records, key, output):
    """Emit the symbols as assembly data, the same way the stubs were emitted."""
    lines = ["/* Owner-root policy generated by peridot tools/emit-owner-policies.py. */"]
    lines.append(".globl _verified_root_key")
    lines.append(".section __DATA,__data")
    lines.append(".p2align 3")
    lines.append("_verified_root_key:")
    lines.append("    .byte " + ",".join(str(b) for b in key))
    for record in records:
        data = bytes.fromhex(record["header"]) + bytes.fromhex(record["signature"])
        ident = record["name"].replace(" ", "_")
        lines.append(f"    .p2align 3")
        lines.append(f"_policy_{ident}:")
        lines.append("    .byte " + ",".join(str(b) for b in data))
    lines.append(".globl _verified_root_policies")
    lines.append(".p2align 3")
    lines.append("_verified_root_policies:")
    for record in records:
        ident = record["name"].replace(" ", "_")
        lines.append(f"    .quad _policy_{ident}")
        lines.append(f"    .quad {HEADER_BYTES + SIGNATURE_BYTES}")
    lines.append(".globl _verified_root_policy_count")
    lines.append(".p2align 3")
    lines.append("_verified_root_policy_count:")
    lines.append(f"    .quad {len(records)}")
    lines.append("")
    pathlib.Path(output).write_text("\n".join(lines))
    print(f"wrote {output}: assembly data for {len(records)} policies")
if __name__ == "__main__":
    main()
